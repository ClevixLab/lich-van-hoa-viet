Y_TABLE_END = 2019.0
Y_BRIDGE_END = 2800.0
Y_MIN = 1895.0


def parabola(y):
    u = (y - 1825.0) / 100.0
    return -320.0 + 32.5 * u * u


def parabola_slope(y):
    """dΔT/dY của parabol (giây/năm)."""
    return 2.0 * 32.5 * (y - 1825.0) / 10000.0


# Giá trị và độ dốc ở hai đầu đoạn nối (tính một lần, cùng thứ tự phép tính như lõi).
_K0, _K1, _A0, _A1, _A2, _A3 = S15_2020[-1]
P0 = _A0 + _A1 + _A2 + _A3                       # ΔT(2019.0) theo hàng cuối, t = 1
M0 = (_A1 + 2.0 * _A2 + 3.0 * _A3) / (_K1 - _K0)  # dΔT/dY tại 2019.0 (giây/năm)
P1 = parabola(Y_BRIDGE_END)                      # ΔT(2800.0) theo parabol
M1 = parabola_slope(Y_BRIDGE_END)                # dΔT/dY tại 2800.0


def decimal_year(jd_tt):
    """Năm thập phân dùng cho ΔT: Y = 2000 + (JD_TT − 2451544.5)/365.2425."""
    return 2000.0 + (jd_tt - 2451544.5) / 365.2425


def delta_t(y):
    """ΔT (giây) tại năm thập phân Y (1895.0 ≤ Y; ngoài miền → ValueError)."""
    if y != y or y < Y_MIN:
        raise ValueError("ngoài miền ΔT của Jpl")
    if y < Y_TABLE_END:
        for k0, k1, a0, a1, a2, a3 in S15_2020:
            if k0 <= y < k1:
                t = (y - k0) / (k1 - k0)
                return a0 + t * (a1 + t * (a2 + t * a3))
        raise AssertionError("bảng S15 không phủ Y")
    if y < Y_BRIDGE_END:
        h = Y_BRIDGE_END - Y_TABLE_END
        s = (y - Y_TABLE_END) / h
        s2 = s * s
        s3 = s2 * s
        h00 = 2.0 * s3 - 3.0 * s2 + 1.0
        h10 = s3 - 2.0 * s2 + s
        h01 = -2.0 * s3 + 3.0 * s2
        h11 = s3 - s2
        return h00 * P0 + h10 * h * M0 + h01 * P1 + h11 * h * M1
    return parabola(y)


